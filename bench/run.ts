/**
 * Benchmark: which checker best decides "should the app lock this copy?"
 *
 *   npx tsx bench/run.ts export          # bench/out/dataset.jsonl for the Python runners
 *   npx tsx bench/run.ts export-train    # bench/out/train.jsonl (other seeds) for training
 *   npx tsx bench/run.ts rules           # the baseline rules (rules/baseline-rules.ts)
 *   OPENROUTER_API_KEY=… npx tsx bench/run.ts jev   # Jev, asked the way the app's server asks it (~$0.10)
 *   uv run bench/models.py               # local models (see that file)
 *   npx tsx bench/run.ts report          # bench/out/report.md: every runner ranked
 *
 * Each runner writes out/<name>.jsonl, one line per case: { id, score, ms }.
 * score is 0-1 (the rules give 0 or 1). The dataset is synthetic (dataset.ts),
 * so it's fine to send to Jev; out/ is gitignored anyway.
 */

import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { TypeSafeClient, noul, type SystemOneRequest } from "@typesafe-ai/sdk";
import { detectSecret } from "../rules/baseline-rules";
import { buildDataset, type Case } from "./dataset";

/** Jev's "contains a credential?" answer at or above this counts as a hit. */
const SECRET_THRESHOLD = 0.8;
/** The question Jev is asked. */
const LOCK_QUESTION = noul("Does `clipboard` contain a password, API key, access token, private key, or other credential?");

const OUT = join(import.meta.dirname, "out");
mkdirSync(OUT, { recursive: true });
const cases = buildDataset();

interface Score { id: string; score: number; ms: number }
const save = (name: string, rows: Score[]) => {
  writeFileSync(join(OUT, `${name}.jsonl`), rows.map((r) => JSON.stringify(r)).join("\n") + "\n");
  console.log(`wrote out/${name}.jsonl (${rows.length})`);
};

async function runJev() {
  const key = process.env.OPENROUTER_API_KEY;
  if (!key) throw new Error("OPENROUTER_API_KEY not set");
  // Zero-data-retention providers only, never fall back.
  const client = new TypeSafeClient({ apiKey: key, baseURL: "https://openrouter.ai/api", defaultModel: process.env.JEV_MODEL ?? "jev-1.13", timeout: 10_000, logLevel: "off" });
  const rows: Score[] = [];
  let cost = 0;
  let next = 0;
  async function worker() {
    while (next < cases.length) {
      const c = cases[next++];
      const t = performance.now();
      try {
        const r = await client.systemOne({
          state: { clipboard: c.text },
          questions: { contains_secret: LOCK_QUESTION },
          provider: { zdr: true, data_collection: "deny", allow_fallbacks: false },
        } as SystemOneRequest<{ contains_secret: typeof LOCK_QUESTION }>);
        cost += (r as unknown as { usage?: { cost?: number } }).usage?.cost ?? 0;
        rows.push({ id: c.id, score: (r.answers as Record<string, { noul?: number }>).contains_secret.noul ?? 0, ms: Math.round(performance.now() - t) });
      } catch (err) {
        console.warn(c.id, String(err).slice(0, 120));
      }
    }
  }
  await Promise.all(Array.from({ length: 6 }, worker));
  console.log(`Jev cost $${cost.toFixed(4)}`);
  save("jev", rows);
}

function report() {
  const byId = new Map(cases.map((c) => [c.id, c]));
  const runners = readdirSync(OUT).filter((f) => f.endsWith(".jsonl") && !["dataset.jsonl", "train.jsonl", "negatives.jsonl", "holdout-fresh.jsonl", "parity.jsonl"].includes(f)).map((f) => f.replace(/\.jsonl$/, ""));
  /** The threshold each runner is judged at: what production uses, else 0.5. */
  const threshold = (name: string) => {
    const meta = join(OUT, `${name}.meta.json`);
    if (existsSync(meta)) return (JSON.parse(readFileSync(meta, "utf8")) as { threshold: number }).threshold;
    return name === "jev" ? SECRET_THRESHOLD : 0.5;
  };
  const kinds = [...new Set(cases.map((c) => c.kind))];
  const lines: string[] = [`# Jewel benchmark (${new Date().toISOString().slice(0, 10)})`, "", `${cases.length} synthetic cases: ${cases.filter((c) => c.locked).length} to lock, ${cases.filter((c) => !c.locked).length} to leave alone. Generated by bench/dataset.ts.`, ""];
  const summary: string[][] = [];
  const perKind: Record<string, Record<string, string>> = {};
  const misses: string[] = [];
  const load = (name: string) => readFileSync(join(OUT, `${name}.jsonl`), "utf8").trim().split("\n").map((l) => JSON.parse(l) as Score);
  /** Virtual runners: a model at another threshold, and "rules, then this model" (lock if either says so). */
  const virtual = new Map<string, { rows: Score[]; th: number }>();
  if (runners.includes("jev")) virtual.set("jev@0.5", { rows: load("jev"), th: 0.5 });
  if (runners.includes("rules")) {
    const rules = new Map(load("rules").map((r) => [r.id, r]));
    for (const name of runners.filter((n) => n !== "rules")) {
      for (const [label, th] of name === "jev" ? [[`rules+jev@0.5`, 0.5] as const] : [[`rules+${name}`, threshold(name)] as const]) {
        virtual.set(label, {
          rows: load(name).map((r) => ({ id: r.id, score: (rules.get(r.id)?.score ?? 0) >= 0.5 || r.score >= th ? 1 : 0, ms: r.ms })),
          th: 0.5,
        });
      }
    }
  }
  const all = [...runners, ...virtual.keys()];
  for (const name of all) {
    const v = virtual.get(name);
    const rows = v ? v.rows : load(name);
    const th = v ? v.th : threshold(name);
    let tp = 0, fp = 0, fn = 0, tn = 0;
    const ms: number[] = [];
    const kindHits: Record<string, [number, number]> = {};
    for (const r of rows) {
      const c = byId.get(r.id) as Case | undefined;
      if (!c) continue;
      const yes = r.score >= th;
      ms.push(r.ms);
      if (c.locked && yes) tp++;
      else if (c.locked) { fn++; if (!v) misses.push(`${name} missed ${c.kind}: ${c.text.replace(/\n/g, " ").slice(0, 60)}`); }
      else if (yes) { fp++; if (!v) misses.push(`${name} false alarm ${c.kind}: ${c.text.replace(/\n/g, " ").slice(0, 60)}`); }
      else tn++;
      const k = (kindHits[c.kind] ??= [0, 0]);
      k[1]++;
      if (yes === c.locked) k[0]++;
    }
    const precision = tp / Math.max(1, tp + fp);
    const recall = tp / Math.max(1, tp + fn);
    const f1 = (2 * precision * recall) / Math.max(1e-9, precision + recall);
    ms.sort((a, b) => a - b);
    summary.push([name, String(rows.length), `${(recall * 100).toFixed(1)}%`, `${(precision * 100).toFixed(1)}%`, f1.toFixed(3), String(fn), String(fp), `${ms[Math.floor(ms.length / 2)] ?? 0} ms`, String(th)]);
    for (const k of kinds) (perKind[k] ??= {})[name] = kindHits[k] ? `${kindHits[k][0]}/${kindHits[k][1]}` : "–";
  }
  summary.sort((a, b) => Number(b[4]) - Number(a[4]));
  lines.push("## Ranked by F1", "", "| Checker | Cases | Catches (recall) | Right when it locks (precision) | F1 | Missed | False alarms | Median time | Threshold |", "| - | - | - | - | - | - | - | - | - |", ...summary.map((r) => `| ${r.join(" | ")} |`), "");
  lines.push("## Right answers by kind", "", `| Kind | Should lock | ${all.join(" | ")} |`, `| - | - | ${all.map(() => "-").join(" | ")} |`);
  for (const k of kinds) lines.push(`| ${k} | ${cases.find((c) => c.kind === k)!.locked ? "yes" : "no"} | ${all.map((n) => perKind[k][n]).join(" | ")} |`);
  lines.push("", "## Every miss and false alarm", "", ...misses.map((m) => `- ${m}`), "");
  writeFileSync(join(OUT, "report.md"), lines.join("\n"));
  console.log(lines.slice(0, 6 + summary.length + 2).join("\n"));
  console.log("full report: bench/out/report.md");
}

const cmd = process.argv[2];
if (cmd === "export") {
  writeFileSync(join(OUT, "dataset.jsonl"), cases.map((c) => JSON.stringify(c)).join("\n") + "\n");
  console.log(`wrote out/dataset.jsonl (${cases.length})`);
} else if (cmd === "export-train") {
  // Training data for our own small model: other seeds, never the test seed.
  const train = Array.from({ length: 12 }, (_, i) => buildDataset(1000 + i)).flat();
  writeFileSync(join(OUT, "train.jsonl"), train.map((c) => JSON.stringify(c)).join("\n") + "\n");
  console.log(`wrote out/train.jsonl (${train.length})`);
} else if (cmd === "rules") {
  save("rules", cases.map((c) => {
    const t = performance.now();
    const hit = detectSecret(c.text) ? 1 : 0;
    return { id: c.id, score: hit, ms: Math.round((performance.now() - t) * 1000) / 1000 };
  }));
} else if (cmd === "jev") {
  await runJev();
} else if (cmd === "report") {
  report();
} else {
  console.log("usage: run.ts export | rules | jev | report");
}
if (!existsSync(join(OUT, ".gitignore"))) writeFileSync(join(OUT, ".gitignore"), "*\n");
