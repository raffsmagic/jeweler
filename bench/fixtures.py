"""Freeze Python's answers (the gate and every shipped model's score) for a fixed set of
synthetic texts into test/fixtures/parity.json, so the library's tests check the TypeScript
runtime against Python without retraining. Everything here is fake: the hand-written everyday
copies, seeded random passwords and edge cases. Re-run after any model or feature change:

    uv run bench/fixtures.py && npm test
"""
import json, math, random, string, sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
from jewel import DEFAULT_FEATURES, features, gated  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent

rng = random.Random(20261110)
WORDS = ["river", "maple", "orbit", "candle", "harbor", "violet", "tiger", "pepper", "falcon", "garden"]
SYMS = "!@#$%^&*-_=+?."


def rand(alphabet: str, n: int) -> str:
    return "".join(rng.choice(alphabet) for _ in range(n))


generated = []
for _ in range(40):
    generated.append(rand(string.ascii_letters + string.digits, rng.randint(8, 32)))
    generated.append(rand(string.ascii_letters + string.digits + SYMS, rng.randint(8, 24)))
    generated.append(rng.choice(WORDS).capitalize() + str(rng.randint(1, 9999)) + rng.choice(["", "!", "?", "#"]))
    generated.append("-".join(rand(string.ascii_lowercase + string.digits, 4) for _ in range(rng.randint(2, 4))))
    generated.append(rand(string.ascii_lowercase, rng.randint(8, 16)))

edge = [
    "Summer2026!", "nbB-Pdv-v3v-WUc", "héllo wörld 😀", "  padded  ", "ПАРОЛЬ123!", "a" * 300,
    "", "short", "1234567", "12345678", "12345678a", "a" * 64, "a" * 65, "Ab3" + "x" * 61, "Ab3" + "x" * 62,
    "https://example.com/x", "HTTP://EXAMPLE.COM", "www.example.com", "/usr/local/bin", "~/notes.txt",
    "ftp://host/file", "someone@example.com", "first.last+tag@mail.example.org", "report.json", "holiday.mp4",
    "archive.tar.gz", "v1.2.3-beta", "two words", "tab\tinside", "\n\nnewlines9Ab\n", "IDENTIFIER_NAME_2",
    "camelCaseVariable", "snake_case_name", "😀😀😀😀😀😀😀😀", "Ünïcödé123", "ǅungla99Zz", "ΣΊΣΥΦΟΣ2026",
    "İstanbul2026", "straße2026!", "ﬁnancial99", "abc defghij", "　wide　space99",
    "﻿bomPrefix9", "jöhn@exämple.com", "名前はパスワード2026", "x​zero​width9",
    "\x1cfile9Sep\x1f", "abc\x1cdefgh9", "\x85lead9Abcdef", "trail9Abcdef\x85", "mid\ufeffdle9Abc", "jöhn@exämple.co_uk", "ñame_1@dömain.test", "Ab3\u2028defgh", "MiXeD-CaSe_123!", "0x1F2e3D4c", "deadBEEFcafe1234",
]

texts, seen = [], set()
for t in [i["text"] for i in json.loads((ROOT / "bench" / "everyday.json").read_text())["items"]] + generated + edge:
    if t not in seen:
        seen.add(t)
        texts.append(t)

models = {}
for path in sorted((ROOT / "models").glob("jeweler-v*.json")):
    m = json.loads(path.read_text())
    models[str(m["version"])] = m


def score(m: dict, text: str) -> float:
    cfg = m.get("features") or {**DEFAULT_FEATURES, "dim": m["dim"]}
    w = m["weights"]
    z = m["bias"] + sum(w.get(str(k), 0.0) * v for k, v in features(text, cfg).items())
    return 1 / (1 + math.exp(-z))


rows = [{"text": t, "gated": gated(t), "scores": {v: score(m, t) for v, m in models.items()}} for t in texts]
out = ROOT / "test" / "fixtures" / "parity.json"
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text(json.dumps({"note": "Generated by bench/fixtures.py; synthetic texts only.", "models": sorted(models), "rows": rows}, ensure_ascii=False, indent=0) + "\n")
print(f"wrote {out.relative_to(ROOT)}: {len(rows)} texts x models {', '.join(sorted(models))}")
